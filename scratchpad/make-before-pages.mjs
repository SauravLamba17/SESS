// Builds scripts/loadtest/before/pages.ts from the git HEAD versions of the four
// dashboard pages: each page's data loader, verbatim, with the auth call turned
// into a parameter and its changed lib imports pointed at the HEAD copies.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const head = (p) => execSync(`git show HEAD:${p}`, { encoding: "utf8" }).replace(/\r\n/g, "\n");
const slice = (src, start, end) => {
  const i = src.indexOf(start), j = src.indexOf(end, i);
  if (i < 0 || j < 0) throw new Error(`markers: ${start}`);
  return src.slice(i, j);
};
const must = (s, a, b) => { if (!s.includes(a)) throw new Error(`missing: ${a}`); return s.replace(a, b); };

let admin = slice(head("app/admin/page.tsx"), "/** Hours after check-in", "export default async function");
admin = must(admin, "async function load() {", "export async function adminBefore() {");

const hrSrc = head("app/hr/page.tsx");
let hrNotif = slice(hrSrc, "async function loadNotifications() {", "/**\n * Every figure on this dashboard");
hrNotif = must(hrNotif, "async function loadNotifications() {\n  const userId = await getEffectiveUserId();", "export async function hrNotificationsBefore(userId: string) {");
let hrLoad = slice(hrSrc, "async function load() {", "/** Whole-percent share");
hrLoad = must(hrLoad, "async function load() {", "export async function hrFiguresBefore() {");

let mgr = slice(head("app/manager/page.tsx"), "async function load() {", "export default async function");
mgr = must(mgr, "async function load() {\n  const userId = await getEffectiveUserId();", "export async function managerBefore(userId: string) {");

let emp = slice(head("app/employee/page.tsx"), "async function loadMetrics() {", "export default async function");
emp = must(emp, "async function loadMetrics() {\n  const userId = await getEffectiveUserId();", "export async function employeeBefore(userId: string) {");

const out = `// GENERATED by scratchpad/make-before-pages.mjs from git HEAD — the dashboard
// loaders exactly as they were before the query-count change, for the parity
// test (scripts/loadtest/dashboard-parity.ts). Test-only; never imported by the app.
// @ts-nocheck
import { db } from "@/lib/db";
import { getDepartments } from "@/lib/cache/departments";
import { getTeamRoster } from "@/lib/cache/employees";
import { scoreOutOfFive } from "@/lib/appraisal/display";
import { computeHeadcount, headcountOn } from "@/lib/reports/headcount";
import { computeRecruitmentFunnel } from "@/lib/reports/recruitment-funnel";
import { parseRange, ymd, monthKey } from "@/lib/reports/range";
import { startOfDay, currentPeriod } from "@/lib/period";
import type { Role } from "@/lib/auth-types";
// The HEAD copies of every lib function this change touched:
import { moduleToggleValues } from "./system-settings.ts";
import { getHrDashboardTotals, getPendingLeaveCount } from "./dashboard-cache.ts";
import { loadOwnAttendance } from "./own-summary.ts";
import { ownIdleTotals } from "./idle-aggregate.ts";
export { loadToday as loadTodayBefore } from "./today.ts";

// HEAD lib/data/scope.ts — the two-statement form.
function getEmployeeByClerkId(clerkId: string) {
  return db.user.findUnique({ where: { clerkId }, include: { employee: true } }).then((u) => u?.employee ?? null);
}
function getUserByClerkId(clerkId: string) {
  return db.user.findUnique({ where: { clerkId }, select: { id: true, role: true, employeeId: true } });
}

${admin}
${hrNotif}
${hrLoad}
${mgr}
${emp}`;
writeFileSync("scripts/loadtest/before/pages.ts", out);
console.log("wrote", out.split("\n").length, "lines");

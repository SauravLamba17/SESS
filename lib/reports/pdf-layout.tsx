/**
 * The shared report PDF layout — three primitives, composed by all ten report
 * templates in lib/reports/pdf/.
 *
 *   <ReportDocument>  page frame, branded header (title, range, generated-by /
 *                     generated-at) and the fixed footer
 *   <SummaryStats>    the strip of headline numbers at the top of a report
 *   <DataTable>       columns + rows, one consistent table style
 *
 * No report template writes its own header, footer or table styling. Styling
 * intentionally mirrors lib/payroll/pdf.tsx (same Helvetica, same rule under
 * the company name, same muted footer) so a report and a payslip read as
 * documents from one system.
 */

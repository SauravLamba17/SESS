export type CsvCell = string | number | null | undefined;

export interface CsvSection {
  /** Printed as a title row above the section's header row. */
  title: string;
  headers: string[];
  rows: CsvCell[][];
}

/**
 * RFC-4180 escaping: a field is quoted when it contains a comma, a quote, or a
 * newline, and embedded quotes are doubled. null/undefined become an empty
 * field — never the string "null" — so a spreadsheet shows a blank, matching
 * the "—" the PDF prints for missing data.
 */
export function escapeCsvCell(value: CsvCell): string {
  if (value === null || value === undefined) return "";
  const s = String(value);
  if (/[",\r\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

function sectionToLines(section: CsvSection): string[] {
  const lines = [escapeCsvCell(section.title)];
  lines.push(section.headers.map(escapeCsvCell).join(","));
  for (const row of section.rows) lines.push(row.map(escapeCsvCell).join(","));
  return lines;
}

/**
 * Serialize one or more sections into a single CSV document.
 *
 * Multi-section rather than one flat table because these reports genuinely have
 * several shapes (summary, by-department, by-employee). Sections are separated
 * by a blank line and introduced by a title row, which every spreadsheet opens
 * correctly and a human can read top to bottom.
 *
 * CRLF line endings per RFC 4180 — Excel on Windows is the overwhelmingly
 * likely destination for these files.
 */
export function serializeCsv(sections: CsvSection[], meta?: CsvMeta): string {
  const blocks: string[][] = [];
  if (meta) {
    blocks.push([
      escapeCsvCell(meta.title),
      ["Period", meta.startLabel, "to", meta.endLabel].map(escapeCsvCell).join(","),
      ["Scope", meta.scopeLabel].map(escapeCsvCell).join(","),
      ["Generated by", meta.generatedBy].map(escapeCsvCell).join(","),
      ["Generated at", meta.generatedAt.toISOString()].map(escapeCsvCell).join(","),
    ]);
  }
  for (const s of sections) blocks.push(sectionToLines(s));
  return blocks.map((b) => b.join("\r\n")).join("\r\n\r\n") + "\r\n";
}

export interface CsvMeta {
  title: string;
  startLabel: string;
  endLabel: string;
  scopeLabel: string;
  generatedBy: string;
  generatedAt: Date;
}

// ── One section-builder per report. Reads results, computes nothing. ───────

export function headcountCsv(r: HeadcountResult): CsvSection[] {
  return [
    {
      title: "Summary",
      headers: ["Measure", "Value"],
      rows: [
        ["Active headcount", r.totalActive],
        ["Departments", r.departmentCount],
        ["Headcount at period start", r.atRangeStart],
        ["Headcount at period end", r.atRangeEnd],
        ["Net change", r.netChange],
      ],
    },
    {
      title: "Headcount by department",
      headers: ["Department", "Employees"],
      rows: r.byDepartment.map((d) => [d.department, d.count]),
    },
  ];
}

export function attendanceCsv(r: AttendanceResult): CsvSection[] {
  return [
    {
      title: "Summary",
      headers: ["Measure", "Value"],
      rows: [
        ["Days punched", r.totalPunchDays],
        ["On time", r.onTimeCount],
        ["Late", r.lateCount],
        ["Late %", r.latePct],
        ["Average punch-in (org)", r.orgAvgPunchIn],
        ["Average punch-in minutes since midnight", r.orgAvgPunchInMinutes],
        ["Average punch-in method", r.orgAvgPunchInMethod],
        ["Expected employee-weekdays", r.expectedWeekdayCount],
        ["Days with no punch", r.noPunchDays],
      ],
    },
    {
      title: "By department",
      headers: [
        "Department", "Employees", "Days punched", "Late", "Late %",
        "Avg punch-in", "Mean type",
      ],
      rows: r.byDepartment.map((d) => [
        d.department, d.employees, d.punchDays, d.lateCount, d.latePct,
        d.avgPunchIn, d.avgPunchInMethod,
      ]),
    },
    {
      title: "By employee",
      headers: [
        "Employee code", "Name", "Department", "Days punched", "Late", "On time",
        "Late %", "Avg late minutes", "Avg punch-in", "Mean type",
      ],
      rows: r.byEmployee.map((e) => [
        e.employeeCode, e.name, e.department, e.punchDays, e.lateCount, e.onTimeCount,
        e.latePct, e.avgLateMinutes, e.avgPunchIn, e.avgPunchInMethod,
      ]),
    },
  ];
}


// CSV export for the nine data-heavy reports.
//
// ─── WHY THIS CANNOT DRIFT FROM THE PDF ──────────────────────────────────
// Nothing here computes anything. Every function below takes the SAME result
// object the PDF template renders — the one produced by the report's single
// pure compute function in this directory — and flattens it into rows. The API
// route calls compute() once and hands the identical object to either the PDF
// renderer or this module, so a CSV and a PDF of the same report over the same
// range are two renderings of one calculation, not two calculations.
// ─────────────────────────────────────────────────────────────────────────
//
// Board Summary is deliberately absent: it is a one-page narrative of headline
// figures, and its detail already lives in the nine reports it summarises.
//
// Pure. No DB access, no dependency — a CSV writer is a dozen lines.


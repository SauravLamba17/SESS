// ── Primitive 1: the document frame + header ───────────────────────────────

export interface ReportMeta {
  /** e.g. "Attendance & Punctuality". */
  title: string;
  startLabel: string; // "YYYY-MM-DD"
  endLabel: string;
  generatedBy: string;
  generatedAt: Date;
  /** "Organisation-wide", "Your team (8 employees)", "Assembly department". */
  scopeLabel: string;
}

function iso(d: Date): string {
  return d.toISOString().slice(0, 16).replace("T", " ");
}

export function ReportDocument({
  meta,
  children,
}: {
  meta: ReportMeta;
  children: React.ReactNode;
}) {
  return (
    <Document
      title={`${meta.title} ${meta.startLabel} to ${meta.endLabel}`}
      author={COMPANY_NAME}
      subject={`${meta.title} — ${meta.scopeLabel}`}
    >
      <Page size="A4" orientation="portrait" style={s.page}>
        <Text style={s.company}>{COMPANY_NAME}</Text>
        <Text style={s.docTitle}>{meta.title.toUpperCase()}</Text>
        <View style={s.rule} />

        <View style={s.metaRow}>
          <View style={s.metaCell}>
            <Text style={s.metaLabel}>Period</Text>
            <Text style={s.metaValue}>
              {meta.startLabel} to {meta.endLabel}
            </Text>
          </View>
          <View style={s.metaCell}>
            <Text style={s.metaLabel}>Scope</Text>
            <Text style={s.metaValue}>{meta.scopeLabel}</Text>
          </View>
          <View style={s.metaCell}>
            <Text style={s.metaLabel}>Generated by</Text>
            <Text style={s.metaValue}>{meta.generatedBy}</Text>
          </View>
          <View style={s.metaCell}>
            <Text style={s.metaLabel}>Generated at</Text>
            <Text style={s.metaValue}>{iso(meta.generatedAt)} UTC</Text>
          </View>
        </View>

        {children}

        <Text style={s.footer} fixed>
          Computer-generated report · {COMPANY_NAME} · figures cover{" "}
          {meta.startLabel} to {meta.endLabel} only
        </Text>
      </Page>
    </Document>
  );
}

// ── Primitive 2: the summary-stats strip ───────────────────────────────────

export interface SummaryStat {
  label: string;
  value: string | number;
  hint?: string;
}

export function SummaryStats({ stats }: { stats: SummaryStat[] }) {
  if (stats.length === 0) return null;
  return (
    <View style={s.statsRow}>
      {stats.map((st) => (
        <View style={s.statBox} key={st.label}>
          <Text style={s.statLabel}>{st.label}</Text>
          <Text style={s.statValue}>{String(st.value)}</Text>
          {st.hint ? <Text style={s.statHint}>{st.hint}</Text> : null}
        </View>
      ))}
    </View>
  );
}

// ── Primitive 3: the data table ────────────────────────────────────────────

export interface TableColumn<T> {
  /** Header text. */
  label: string;
  /** Percentage width, e.g. "25%". Should sum to 100 across the columns. */
  width: string;
  align?: "left" | "right";
  /** Cell text. Returning "—" for missing data is the convention everywhere. */
  value: (row: T) => string;
}

export function DataTable<T>({
  title,
  columns,
  rows,
  emptyMessage = "No data in this period.",
  maxRows,
}: {
  title?: string;
  columns: TableColumn<T>[];
  rows: T[];
  emptyMessage?: string;
  /** Cap long tables; the count of omitted rows is printed underneath. */
  maxRows?: number;
}) {
  const shown = maxRows ? rows.slice(0, maxRows) : rows;
  const omitted = rows.length - shown.length;

  return (
    <View wrap>
      {title ? <Text style={s.sectionTitle}>{title.toUpperCase()}</Text> : null}
      <View style={s.tableBox}>
        <View style={s.tHead} fixed>
          {columns.map((c) => (
            <Text
              key={c.label}
              style={[s.cell, { width: c.width, textAlign: c.align ?? "left" }]}
            >
              {c.label}
            </Text>
          ))}
        </View>
        {shown.map((row, i) => (
          <View style={i % 2 === 1 ? [s.tRow, s.tRowAlt] : s.tRow} key={i} wrap={false}>
            {columns.map((c) => (
              <Text
                key={c.label}
                style={[s.cell, { width: c.width, textAlign: c.align ?? "left" }]}
              >
                {c.value(row)}
              </Text>
            ))}
          </View>
        ))}
        {shown.length === 0 && <Text style={s.emptyRow}>{emptyMessage}</Text>}
      </View>
      {omitted > 0 && (
        <Text style={s.note}>
          Showing the first {shown.length} of {rows.length} rows; {omitted} omitted
          for length.
        </Text>
      )}
    </View>
  );
}

/** Explanatory footnote under a table — used for the honest-caveat text. */
export function Note({ children }: { children: React.ReactNode }) {
  return <Text style={s.note}>{children}</Text>;
}

/** Every template ends here. One place that knows how to produce the buffer. */
export function renderReport(element: React.ReactElement): Promise<Buffer> {
  return renderToBuffer(element);
}

/** Formatting shared by the templates. */
export function fmtPct(n: number | null): string {
  return n === null ? "—" : `${n}%`;
}
export function fmtNum(n: number | null): string {
  return n === null ? "—" : String(n);
}
